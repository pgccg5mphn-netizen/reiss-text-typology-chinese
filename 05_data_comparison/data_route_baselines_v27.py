#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
data_route_baselines_v27.py
Section 4 data-route validation: full reproduction script for the theory-driven
route vs the two data-driven baselines.

Final paper configuration (do not change):
- Theory route: 13 theory-driven features (feature_extractor_v9_4, paper-final),
  LogisticRegression(C=1.0, class_weight='balanced'), StandardScaler fitted
  within each fold
- Character-level baseline (primary baseline, zero word-unit assumption):
  TfidfVectorizer(analyzer='char_wb', ngram_range=(2,4), max_features=5000),
  LogisticRegression(C=1.0, class_weight='balanced')
- Word-level baseline (strong control, carries Chinese word-segmentation
  knowledge): jieba segmentation + TfidfVectorizer(max_features=5000),
  LogisticRegression(C=1.0, class_weight='balanced')

Validation regimes:
- Stratified random 5-fold: StratifiedKFold(5, shuffle=True, random_state=42)
- Leave-one-group-out (LOGO): LeaveOneGroupOut with the group_fine key
  (31 groups as measured: 15 ToRCH genre codes + 16 external sources;
  ToRCH categories are unified to the leading letter genre code, merging the
  short and full spellings)

Corpus: corpus/corpus_relabeled_v27.json (n=1165)

Output: data_route_baselines_v27.json + full console numbers

NOTE on Chinese strings kept below: per-class keys (via LABEL_ZH) and the
Spearman pair keys embed the Chinese corpus labels / feature short names; they
are written verbatim into the reference JSON consumed elsewhere, so they are
not renamed.
"""
import os
import sys
import json
import numpy as np
import warnings
from collections import Counter

warnings.filterwarnings('ignore')

import jieba
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import StratifiedKFold, LeaveOneGroupOut
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import (
    accuracy_score, f1_score, precision_recall_fscore_support, confusion_matrix
)
from scipy.stats import spearmanr

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS_PATH = os.path.join(BASE_DIR, 'corpus', 'corpus_relabeled_v27.json')
RES_DIR = os.path.join(BASE_DIR, 'wordlists')
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data_route_baselines_v27.json')
sys.path.insert(0, os.path.join(BASE_DIR, '01_feature_engineering'))
from feature_extractor_v9_4 import TextTypeFeatureExtractor  # noqa: E402

LABEL_ORDER = ['informative', 'expressive', 'infective']
# Chinese display labels; these also become the per-class keys of the saved JSON.
LABEL_ZH = {'informative': '信息型', 'expressive': '表情型', 'infective': '感染型'}
SEED = 42


def _torch_genre_code(category):
    """Unify a ToRCH category into its letter genre code.

    The corpus was imported in two batches, and 'category' has both a short and
    a full spelling: the first batch (generated by torch2014_segmenter.py) uses
    'A-新闻报道' (letter-prefixed), the second batch uses the bare code 'A'.
    Splitting one genre into two groups would break the leakage-free design
    (when one group is held out for testing, the other spelling of the same
    genre would remain in training), so the leading letter is taken here.
    Values that are not genre codes (e.g. a mis-filled 'infective') are kept
    as-is.
    """
    if not category:
        return '?'
    c = str(category).strip()
    if c.lower() == 'infective':
        return c
    return c.split('-')[0].strip() or '?'


def load_corpus(path):
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    texts, labels, groups = [], [], []
    for item in data:
        dd = item.get('data', {})
        text = (dd.get('text') or '').strip()
        if not text:
            continue
        annos = item.get('annotations') or []
        if not annos or not annos[0].get('result'):
            continue
        choices = annos[0]['result'][0].get('value', {}).get('choices') or []
        if not choices:
            continue
        texts.append(text)
        labels.append(choices[0])
        # group_fine: ToRCH samples grouped by category (letter genre code,
        # short/full spellings merged); external samples grouped by source_file
        if dd.get('source_file') == 'ToRCH2014':
            groups.append('ToRCH::' + _torch_genre_code(dd.get('category')))
        else:
            groups.append('EXT::' + str(dd.get('source_file') or '?'))
    return texts, labels, np.array(groups)


def run_cv(X, y, groups, C, scale, splitter):
    """Return out-of-fold predictions and out-of-fold probabilities."""
    pred = np.zeros(len(y), dtype=int)
    prob = np.zeros((len(y), 3))
    for tr, te in splitter.split(X, y, groups):
        if scale:
            sc = StandardScaler().fit(X[tr])
            a, b = sc.transform(X[tr]), sc.transform(X[te])
            clf = LogisticRegression(C=1.0, max_iter=1000, class_weight='balanced',
                                     solver='lbfgs', random_state=SEED)
        else:
            a, b = X[tr], X[te]
            clf = LogisticRegression(C=C, max_iter=1000, class_weight='balanced',
                                     solver='lbfgs', random_state=SEED)
        clf.fit(a, y[tr])
        pred[te] = clf.predict(b)
        prob[te] = clf.predict_proba(b)
    return pred, prob


def metrics(y, pred, prob=None):
    acc = accuracy_score(y, pred) * 100
    macro_f1 = f1_score(y, pred, average='macro', zero_division=0)
    pr, rc, f1, _ = precision_recall_fscore_support(y, pred, labels=[0, 1, 2], zero_division=0)
    out = {
        'acc': round(acc, 2),
        'macro_f1': round(macro_f1, 4),
        # per_class keys use the Chinese corpus labels (JSON-consistent)
        'per_class': {LABEL_ZH[LABEL_ORDER[i]]: {'P': round(pr[i] * 100, 1),
                                                 'R': round(rc[i] * 100, 1),
                                                 'F1': round(f1[i] * 100, 1)} for i in range(3)},
        'macro_P': round(pr.mean() * 100, 1),
        'macro_R': round(rc.mean() * 100, 1),
        'macro_F1_pct': round(f1.mean() * 100, 1),
        'confusion': confusion_matrix(y, pred, labels=[0, 1, 2]).tolist(),
    }
    return out


def consistency(y, pa, pb):
    agree = pa == pb
    both_right = (pa == y) & (pb == y)
    both_wrong = (pa != y) & (pb != y)
    only_a = (pa == y) & (pb != y)
    only_b = (pb == y) & (pa != y)
    return {
        'agreement_pct': round(agree.mean() * 100, 1),
        'joint_right_pct': round(both_right.mean() * 100, 1),
        'joint_fail_pct': round(both_wrong.mean() * 100, 1),
        'only_theory_right_pct': round(only_a.mean() * 100, 1),
        'only_baseline_right_pct': round(only_b.mean() * 100, 1),
        'only_theory_right_n': int(only_a.sum()),
        'only_baseline_right_n': int(only_b.sum()),
        'per_class_agreement': {LABEL_ZH[LABEL_ORDER[i]]: round(agree[y == i].mean() * 100, 1) for i in range(3)},
        'per_class_joint_fail': {LABEL_ZH[LABEL_ORDER[i]]: round(both_wrong[y == i].mean() * 100, 1) for i in range(3)},
    }


def main():
    if not os.path.exists(CORPUS_PATH):
        raise FileNotFoundError(CORPUS_PATH)
    texts, labels, groups = load_corpus(CORPUS_PATH)
    y = np.array([LABEL_ORDER.index(l) for l in labels])
    n = len(y)
    print('Corpus: %s' % os.path.basename(CORPUS_PATH))
    print('n=%d  distribution: %s' % (n, {k: v for k, v in Counter(labels).items()}))
    print('group_fine group count: %d' % len(set(groups)))

    # 13 theory-driven features
    ext = TextTypeFeatureExtractor(resource_dir=RES_DIR)
    X13 = ext.extract_batch(texts)
    print('13-dim feature matrix: %s' % str(X13.shape))

    # jieba segmentation
    jieba.initialize()
    jtexts = [' '.join(jieba.cut(t)) for t in texts]

    # Vectorisation
    Xchar = TfidfVectorizer(analyzer='char_wb', ngram_range=(2, 4), max_features=5000).fit_transform(texts)
    Xword = TfidfVectorizer(max_features=5000).fit_transform(jtexts)
    print('Char-level matrix: %s   Word-level matrix: %s' % (Xchar.shape, Xword.shape))

    routes = {
        'theory_13dim': (X13, 1.0, True),
        'char_tfidf': (Xchar, 1.0, False),
        'word_tfidf_jieba': (Xword, 1.0, False),
    }

    result = {'corpus': os.path.basename(CORPUS_PATH), 'n': n,
              'group_fine_n': len(set(groups)), 'routes': {}, 'random_cv': {}, 'logo': {}}

    skf = StratifiedKFold(5, shuffle=True, random_state=SEED)
    logo = LeaveOneGroupOut()
    preds_r, preds_l, probs_r = {}, {}, {}

    print('\n===== Regime 1: stratified random 5-fold =====')
    for name, (X, C, sc) in routes.items():
        p, pr = run_cv(X, y, groups, C, sc, skf)
        preds_r[name], probs_r[name] = p, pr
        m = metrics(y, p)
        result['random_cv'][name] = m
        print('%-18s Acc=%.2f%%  macroF1=%.4f  P/R: inf %.1f/%.1f  exp %.1f/%.1f  opr %.1f/%.1f'
              % (name, m['acc'], m['macro_f1'],
                 m['per_class']['信息型']['P'], m['per_class']['信息型']['R'],
                 m['per_class']['表情型']['P'], m['per_class']['表情型']['R'],
                 m['per_class']['感染型']['P'], m['per_class']['感染型']['R']))

    print('\n===== Regime 2: leave-one-group-out LOGO (%d groups) =====' % len(set(groups)))
    for name, (X, C, sc) in routes.items():
        p, _ = run_cv(X, y, groups, C, sc, logo)
        preds_l[name] = p
        m = metrics(y, p)
        result['logo'][name] = m
        print('%-18s Acc=%.2f%%  macroF1=%.4f' % (name, m['acc'], m['macro_f1']))

    print('\nAccuracy drop (random -> LOGO):')
    for name in routes:
        d = result['random_cv'][name]['acc'] - result['logo'][name]['acc']
        print('  %-18s -%.2fpp' % (name, d))

    # Prediction consistency (random-CV regime)
    print('\n===== Prediction agreement and disagreement (random CV) =====')
    result['consistency'] = {}
    for base in ['char_tfidf', 'word_tfidf_jieba']:
        c = consistency(y, preds_r['theory_13dim'], preds_r[base])
        result['consistency']['theory_vs_' + base] = c
        print('13-dim vs %s: agreement %.1f%%, both right %.1f%%, both wrong %.1f%%, only-13dim %d, only-baseline %d'
              % (base, c['agreement_pct'], c['joint_right_pct'], c['joint_fail_pct'],
                 c['only_theory_right_n'], c['only_baseline_right_n']))

    # Six Spearman correlations (13-dim features vs baseline class probabilities)
    print('\n===== Spearman correlations (13-dim features vs baseline probabilities) =====')
    F = {'F3': 2, 'F6': 5, 'F4': 3, 'F9': 8, 'F8': 7}
    # The Chinese short names are embedded in the saved JSON keys; do not rename.
    pairs = [('F3', '第三人称密度', 'expressive'), ('F6', '义务情态密度', 'infective'),
             ('F4', '事实认知密度', 'informative'), ('F9', '感叹句比例', 'expressive'),
             ('F8', '祈使句比例', 'infective'), ('F3', '第三人称密度', 'infective')]
    result['spearman'] = {}
    for base in ['char_tfidf', 'word_tfidf_jieba']:
        P = probs_r[base]
        d = {}
        for f, zh, cls in pairs:
            ci = LABEL_ORDER.index(cls)
            r, pv = spearmanr(X13[:, F[f]], P[:, ci])
            d['%s_%s_to_%s' % (f, zh, cls)] = {'r': round(float(r), 3), 'p': float(pv)}
            print('  [%s] %s vs P(%s): r=%+.3f' % (base, f, cls, r))
        result['spearman'][base] = d

    # Lexical-overlap robustness: rerun the word-level baseline with the feature
    # word-list items removed from the segmented input
    print('\n===== Lexical-overlap robustness control =====')
    vocab = set()
    for w in [ext.pronouns['first'], ext.pronouns['second'], ext.pronouns['third'],
              ext.factual_cognitive_words, ext.emotion_words, ext.deontic_words,
              ext.imperative_markers, ext.connectives]:
        vocab.update(w)
    print('Feature word-list union: %d words' % len(vocab))
    jstrip = [' '.join([w for w in jieba.cut(t) if w not in vocab]) for t in texts]
    Xstrip = TfidfVectorizer(max_features=5000).fit_transform(jstrip)
    p_strip, prob_strip = run_cv(Xstrip, y, groups, 1.0, False, skf)
    m_strip = metrics(y, p_strip)
    strip_rho = {}
    for f, zh, cls in pairs:
        ci = LABEL_ORDER.index(cls)
        r, _ = spearmanr(X13[:, F[f]], prob_strip[:, ci])
        strip_rho['%s_%s_to_%s' % (f, zh, cls)] = round(float(r), 3)
        print('  stripped %s vs P(%s): r=%+.3f' % (f, cls, r))
    result['lexical_overlap_control'] = {
        'vocab_size': len(vocab),
        'word_tfidf_full_acc': result['random_cv']['word_tfidf_jieba']['acc'],
        'word_tfidf_stripped_acc': m_strip['acc'],
        'acc_drop_pp': round(result['random_cv']['word_tfidf_jieba']['acc'] - m_strip['acc'], 2),
        'spearman_full': {k: v['r'] for k, v in result['spearman']['word_tfidf_jieba'].items()},
        'spearman_stripped': strip_rho,
    }
    print('Word-level baseline full %.2f%% -> stripped %.2f%% (drop %.2fpp)'
          % (result['random_cv']['word_tfidf_jieba']['acc'], m_strip['acc'],
             result['lexical_overlap_control']['acc_drop_pp']))

    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print('\nResults written to: %s' % OUT_PATH)


if __name__ == '__main__':
    main()
